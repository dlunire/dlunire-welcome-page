<h1 id="pol-tica-de-cookies-dlunire">Política de Cookies — DLUnire</h1>
<p><em>Última actualización: 31 de julio de 2026</em></p>
<h2 id="1-p-gina-de-bienvenida-y-documentaci-n-dlunire-dev-">
    1. Página de Bienvenida y documentación (dlunire.dev)
</h2>
<p>
    La página de bienvenida y la documentación <strong
        >no utiliza cookies de rastreo, analítica ni publicitarias</strong
    >. La adaptación del tema claro/oscuro se realiza mediante la preferencia
    del sistema operativo o navegador del usuario (<code
        >prefers-color-scheme</code
    >), sin necesidad de almacenar ninguna cookie ni preferencia en su
    dispositivo.
</p>
<h2 id="2-tienda-store-dlunire-dev-">2. Tienda (store.dlunire.dev)</h2>
<p>
    En la Tienda pueden utilizarse cookies estrictamente necesarias para el
    funcionamiento del sitio, tales como:
</p>
<ul>
    <li>
        Cookies de sesión, necesarias para mantener el proceso de compra o
        inicio de sesión mientras navega.
    </li>
    <li>
        Cookies impuestas por el proveedor de la pasarela de pago durante el
        proceso de checkout, necesarias para procesar la transacción de forma
        segura.
    </li>
</ul>
<p>
    Estas cookies son de carácter técnico y no se utilizan con fines
    publicitarios ni de perfilamiento comercial.
</p>
<h2 id="3-cookies-de-terceros">3. Cookies de terceros</h2>
<p>
    Si en el futuro se integran herramientas de analítica, soporte al cliente, o
    marketing que impliquen el uso de cookies adicionales, esta política será
    actualizada previamente para reflejar dicho cambio, y se solicitará el
    consentimiento correspondiente cuando la normativa aplicable lo exija.
</p>
<h2 id="4-c-mo-gestionar-las-cookies">4. Cómo gestionar las cookies</h2>
<p>
    Puede configurar su navegador para bloquear o eliminar cookies en cualquier
    momento. Tenga en cuenta que deshabilitar las cookies estrictamente
    necesarias en la Tienda puede afectar el correcto funcionamiento del proceso
    de compra.
</p>
<h2 id="5-cambios-a-esta-pol-tica">5. Cambios a esta política</h2>
<p>
    Esta Política de Cookies puede actualizarse periódicamente. Los cambios
    entrarán en vigor a partir de su publicación en esta página.
</p>
