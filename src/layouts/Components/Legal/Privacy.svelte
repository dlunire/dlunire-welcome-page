<h1 id="pol-tica-de-privacidad-dlunire">Política de Privacidad — DLUnire</h1>
<p><em>Última actualización: 31 de julio de 2026</em></p>
<p>
    Esta Política de Privacidad describe qué datos personales se recopilan, para
    qué se usan y cómo se protegen, según el sitio o servicio de DLUnire
    (Establecimiento de Comercio, operado por David E. Luna M.) que esté
    utilizando. El tratamiento de datos personales se realiza conforme a la Ley
    1581 de 2012 y el Decreto 1377 de 2013 de la República de Colombia (régimen
    de protección de datos personales / Habeas Data).
</p>
<h2 id="1-p-gina-de-bienvenida-y-documentaci-n-dlunire-dev-">
    1. Página de Bienvenida y documentación (dlunire.dev)
</h2>
<p>
    La página de bienvenida y la documentación del framework <strong
        >no recopilan datos personales</strong
    >. No se utilizan formularios, cookies de rastreo, ni analítica de terceros
    en esta sección. Puede navegar, consultar la documentación y copiar los
    ejemplos de código sin que se registre ninguna información suya.
</p>
<h2 id="2-p-gina-principal-con-formularios-">
    2. Página principal (con formularios)
</h2>
<p>
    Si la página principal incluye formularios (por ejemplo, contacto, solicitud
    de licencia gratuita para desarrolladores, o boletín informativo), se
    recopilan únicamente los datos que usted proporciona voluntariamente al
    completarlos, tales como:
</p>
<ul>
    <li>Nombre.</li>
    <li>Correo electrónico.</li>
    <li>Mensaje o motivo de contacto.</li>
    <li>
        Enlace a repositorio, cuando aplique (por ejemplo, para la solicitud de
        licencia comercial gratuita para desarrolladores independientes).
    </li>
</ul>
<p>
    Estos datos se usan exclusivamente para responder a su solicitud, gestionar
    el programa de licencias correspondiente, o enviarle comunicaciones que
    usted haya solicitado explícitamente.
</p>
<h2 id="3-tienda-store-dlunire-dev-">3. Tienda (store.dlunire.dev)</h2>
<p>
    En la Tienda se recopila el <strong>mínimo de datos necesarios</strong> para procesar
    compras y brindar soporte, incluyendo:
</p>
<ul>
    <li>
        Correo electrónico (para confirmar la compra, enviar el código de
        verificación y la licencia).
    </li>
    <li>
        Información de la transacción (estado del pago, monto, fecha, referencia
        de la pasarela) — <strong
            >no se almacenan datos completos de tarjetas de pago</strong
        >; esa información es gestionada directamente por el proveedor de la
        pasarela de pago conforme a sus propias políticas.
    </li>
    <li>Dominio(s) autorizados asociados a una licencia, cuando aplique.</li>
    <li>
        Información técnica mínima (como dirección IP o identificadores de
        sesión) con el único fin de <strong
            >prevenir abuso del sistema de licencias</strong
        > — por ejemplo, evitar que una misma persona obtenga múltiples licencias
        gratuitas del programa para desarrolladores de forma fraudulenta.
    </li>
</ul>
<h3 id="3-1-finalidades-del-tratamiento">3.1 Finalidades del tratamiento</h3>
<p>Los datos recopilados en la Tienda se usan para:</p>
<ul>
    <li>Confirmar su identidad como titular de la compra o solicitud.</li>
    <li>
        Emitir, asociar y administrar licencias (incluyendo el token de dominio
        autorizado).
    </li>
    <li>
        Brindarle soporte en caso de que la compra falle, se le haya debitado
        sin recibir la licencia, o tenga cualquier inconveniente con el
        servicio.
    </li>
    <li>
        Prevenir el uso fraudulento o abusivo del programa de licencias
        gratuitas.
    </li>
</ul>
<h3 id="3-2-con-qui-n-se-comparten-los-datos">
    3.2 Con quién se comparten los datos
</h3>
<p>DLUnire puede compartir datos estrictamente necesarios con:</p>
<ul>
    <li>El proveedor de la pasarela de pago, para procesar la transacción.</li>
    <li>
        El proveedor de envío de correos transaccionales (por ejemplo, Resend),
        únicamente para el envío de códigos de verificación, confirmaciones de
        compra o licencias.
    </li>
</ul>
<p>
    DLUnire no vende ni cede sus datos personales a terceros con fines
    publicitarios.
</p>
<h2 id="4-conservaci-n-de-los-datos">4. Conservación de los datos</h2>
<p>
    Los datos se conservan durante el tiempo necesario para cumplir con las
    finalidades descritas (soporte, gestión de licencias, obligaciones contables
    o legales), y se eliminan o anonimizan cuando dejan de ser necesarios, salvo
    que la ley exija un período de conservación distinto.
</p>
<h2 id="5-sus-derechos">5. Sus derechos</h2>
<p>Conforme a la Ley 1581 de 2012, usted tiene derecho a:</p>
<ul>
    <li>Conocer, actualizar y rectificar sus datos personales.</li>
    <li>
        Solicitar prueba de la autorización otorgada para el tratamiento de sus
        datos.
    </li>
    <li>Ser informado sobre el uso que se ha dado a sus datos.</li>
    <li>
        Revocar la autorización y/o solicitar la supresión de sus datos, cuando
        no exista un deber legal o contractual que lo impida.
    </li>
    <li>
        Presentar quejas ante la Superintendencia de Industria y Comercio (SIC)
        por infracciones a esta normativa.
    </li>
</ul>
<p>
    Para ejercer cualquiera de estos derechos, escriba a <strong
        >info@dlunire.dev</strong
    >.
</p>
<h2 id="6-cambios-a-esta-pol-tica">6. Cambios a esta política</h2>
<p>
    Esta Política de Privacidad puede actualizarse periódicamente. Los cambios
    entrarán en vigor a partir de su publicación en esta página.
</p>
<h2 id="7-contacto">7. Contacto</h2>
<p>
